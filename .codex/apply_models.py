"""Generate local Codex runtime files from a resolved policy (Python 3.11+)."""

import argparse
from copy import deepcopy
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parent
HEADER = "# Generated by Resolve-CodexModels.ps1; edit model-policy.json or templates/.\n"
EFFORTS = {"none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra"}
MODEL_ID = re.compile(r"gpt-\d+(?:\.\d+)*(?:-[a-z][a-z0-9]*)?")


def settings(selection, role):
    if not isinstance(selection, dict) or set(selection) != {"model", "reasoning_effort"}:
        raise ValueError(f"{role}: expected model and reasoning_effort")
    model, effort = selection["model"], selection["reasoning_effort"]
    if not isinstance(model, str) or not MODEL_ID.fullmatch(model):
        raise ValueError(f"{role}: invalid resolved model ID")
    if not isinstance(effort, str) or effort not in EFFORTS:
        raise ValueError(f"{role}: invalid reasoning effort")
    return model, effort


def render(root, selection):
    """Validate the entire selection and all TOML before any runtime writes."""
    required = {"main", "default_subagent", "roles", "catalog_source"}
    if not isinstance(selection, dict) or not required.issubset(selection):
        raise ValueError("Expected main, default_subagent, roles and catalog_source")
    if selection["catalog_source"] not in {"codex-app-server", "oauth-endpoint", "file"}:
        raise ValueError("Unknown catalog source")
    available = selection.get("available_models", [])
    if not isinstance(available, list) or any(not isinstance(model, str) for model in available):
        raise ValueError("available_models must be a list of model IDs")
    templates = root / "templates"
    agents = sorted((templates / "agents").glob("*.toml"))
    if not agents:
        raise ValueError("No agent templates found")
    roles = selection["roles"]
    if not isinstance(roles, dict) or set(roles) != {p.stem for p in agents}:
        raise ValueError("Policy roles must exactly match the agent templates")
    resolved = {name: settings(value, name) for name, value in roles.items()}
    resolved["main"] = settings(selection["main"], "main")
    fallback_model, fallback_effort = settings(selection["default_subagent"], "default_subagent")
    outputs = {}
    for source in [templates / "config.toml", *agents]:
        content = source.read_text(encoding="utf-8-sig")
        original = tomllib.loads(content)
        if "model" in original or "model_reasoning_effort" in original:
            raise ValueError(f"{source}: keep model settings in model-policy.json, not templates")
        role = "main" if source == templates / "config.toml" else source.stem
        model, effort = resolved[role]
        expected = deepcopy(original)
        expected.update(model=model, model_reasoning_effort=effort)
        output = HEADER + f'model = {json.dumps(model)}\nmodel_reasoning_effort = {json.dumps(effort)}\n\n' + content
        if role == "main":
            agents_table = expected.get("agents")
            if not isinstance(agents_table, dict):
                raise ValueError("config template must contain an [agents] table")
            if any(key in agents_table for key in ("default_subagent_model", "default_subagent_reasoning_effort")):
                raise ValueError("Keep default subagent model settings in model-policy.json")
            fallback = (f'\ndefault_subagent_model = {json.dumps(fallback_model)}'
                        f'\ndefault_subagent_reasoning_effort = {json.dumps(fallback_effort)}')
            output, count = re.subn(r"(?m)^\[agents\][ \t]*(?:#[^\n]*)?$", lambda m: m[0] + fallback, output)
            if count != 1:
                raise ValueError("Expected exactly one literal [agents] table header")
            agents_table.update(default_subagent_model=fallback_model,
                                default_subagent_reasoning_effort=fallback_effort)
        if tomllib.loads(output) != expected:
            raise ValueError(f"{source}: generated TOML changed unrelated settings")
        outputs[root / source.relative_to(templates)] = output
    # Deterministic manifest: repeated resolution makes no changes.
    outputs[root / "resolved-models.json"] = json.dumps(selection, indent=2, sort_keys=True) + "\n"
    return outputs


def apply(outputs, check=False):
    stale = [path for path, content in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8-sig") != content]
    if check:
        for path in stale:
            print(f"Out of date: {path.name}")
        return int(bool(stale))
    # Stage all files first, then replace each file atomically.
    staged = {}
    try:
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                             dir=path.parent, prefix=".models-", delete=False) as file:
                staged[path] = Path(file.name)
                file.write(outputs[path])
        for path, temporary in staged.items():
            os.replace(temporary, path)
    finally:
        for temporary in staged.values():
            temporary.unlink(missing_ok=True)
    print(f"Updated {len(stale)} runtime files. Start a new Codex session to use them.")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--selection", type=Path, required=True, help="Resolved JSON from Resolve-CodexModels.ps1")
    parser.add_argument("--root", type=Path, default=ROOT, help="Target .codex directory")
    parser.add_argument("--check", action="store_true", help="Report stale files without changing them")
    args = parser.parse_args()
    try:
        selection = json.loads(args.selection.read_text(encoding="utf-8-sig"))
        return apply(render(args.root.resolve(), selection), args.check)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Model configuration error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
